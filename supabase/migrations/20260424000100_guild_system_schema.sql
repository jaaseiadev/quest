-- =========================================
-- PROFILES
-- =========================================
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  auth_id uuid,
  email text,
  first_name text,
  last_name text,
  display_name text,
  avatar_url text,
  metadata jsonb not null default '{}'::jsonb,
  role_id bigint not null default 1 references public.roles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_profiles_role_id on public.profiles(role_id);

-- =========================================
-- USER STATS
-- =========================================
create table if not exists public.user_stats (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  xp integer not null default 0,
  current_rank_id bigint references public.ranks(id),
  updated_at timestamptz not null default now(),
  constraint user_stats_xp_check check (xp >= 0)
);

create index if not exists idx_user_stats_xp on public.user_stats(xp desc);
create index if not exists idx_user_stats_current_rank_id
  on public.user_stats(current_rank_id);

-- =========================================
-- JOBS
-- =========================================
create table if not exists public.jobs (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text,
  category text,
  company text,
  pay numeric,
  location text,
  slots integer not null default 1,
  reward_xp integer not null default 50,
  status text not null default 'open',
  deadline timestamptz,
  recommended_rank_id bigint references public.ranks(id),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint jobs_slots_check check (slots >= 0),
  constraint jobs_reward_xp_check check (reward_xp >= 0),
  constraint jobs_status_check check (status in ('open', 'closed'))
);

create index if not exists idx_jobs_status on public.jobs(status);
create index if not exists idx_jobs_recommended_rank_id
  on public.jobs(recommended_rank_id);
create index if not exists idx_jobs_category on public.jobs(category);
create index if not exists idx_jobs_created_at on public.jobs(created_at desc);

-- =========================================
-- JOB APPLICATIONS
-- =========================================
create table if not exists public.job_applications (
  id uuid primary key default gen_random_uuid(),
  job_id uuid not null references public.jobs(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending',
  xp_awarded boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint job_applications_unique unique (job_id, user_id),
  constraint job_applications_status_check check (
    status in ('pending', 'accepted', 'in_progress', 'completed', 'rejected')
  )
);

create index if not exists idx_job_applications_job_id
  on public.job_applications(job_id);
create index if not exists idx_job_applications_user_id
  on public.job_applications(user_id);
create index if not exists idx_job_applications_status
  on public.job_applications(status);

-- =========================================
-- PARTIES
-- =========================================
create table if not exists public.parties (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  leader_id uuid references public.profiles(id) on delete set null,
  category text,
  min_rank_id bigint references public.ranks(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_parties_min_rank_id on public.parties(min_rank_id);
create index if not exists idx_parties_leader_id on public.parties(leader_id);

-- =========================================
-- PARTY MEMBERS
-- =========================================
create table if not exists public.party_members (
  id bigint generated by default as identity primary key,
  party_id bigint not null references public.parties(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member',
  joined_at timestamptz not null default now(),
  constraint party_members_unique unique (party_id, user_id),
  constraint party_members_role_check check (role in ('leader', 'member'))
);

create index if not exists idx_party_members_party_id
  on public.party_members(party_id);
create index if not exists idx_party_members_user_id
  on public.party_members(user_id);

