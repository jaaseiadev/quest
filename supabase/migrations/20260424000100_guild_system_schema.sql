  (3, 'Specialist', 500, 999),
  (4, 'Expert', 1000, 1749),
  (5, 'Master', 1750, 2499),
  (6, 'Grandmaster', 2500, null)
on conflict (id) do update set
  name = excluded.name,
  min_xp = excluded.min_xp,
