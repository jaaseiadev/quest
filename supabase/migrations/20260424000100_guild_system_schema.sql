-- =========================================
-- ROLES
-- =========================================
create table if not exists public.roles (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

insert into public.roles (id, name, description)
values
  (1, 'student', 'Default student user'),
  (2, 'admin', 'Administrator user')
on conflict (id) do update set
  name = excluded.name,
  description = excluded.description;

select setval(
  pg_get_serial_sequence('public.roles', 'id'),
  greatest((select max(id) from public.roles), 1),
  true
);

-- =========================================
-- RANKS
-- =========================================
create table if not exists public.ranks (
  id bigint generated by default as identity primary key,
  name text not null unique,
  min_xp integer not null,
  max_xp integer,
  created_at timestamptz not null default now(),
  constraint ranks_xp_check check (
    min_xp >= 0
    and (max_xp is null or max_xp >= min_xp)
  )
);

insert into public.ranks (id, name, min_xp, max_xp)
values
