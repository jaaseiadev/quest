-- =========================================
-- AUTO PROFILE CREATION
-- =========================================
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  default_rank_id bigint;
begin
  select id into default_rank_id
  from public.ranks
  where min_xp = 0
  order by id
  limit 1;

  insert into public.profiles (
    id,
    auth_id,
    email,
    display_name,
    avatar_url,
    role_id
  )
  values (
    new.id,
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    new.raw_user_meta_data->>'avatar_url',
    1
  )
  on conflict (id) do nothing;

  insert into public.user_stats (
    user_id,
    xp,
    current_rank_id
  )
  values (
    new.id,
    0,
    default_rank_id
  )
  on conflict (user_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- =========================================
-- RANK UPDATE TRIGGER
-- =========================================
create or replace function public.update_rank_from_xp()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  resolved_rank_id bigint;
begin
  select id into resolved_rank_id
  from public.ranks
  where new.xp >= min_xp
    and (max_xp is null or new.xp <= max_xp)
  order by min_xp desc
  limit 1;

  new.current_rank_id = resolved_rank_id;
  return new;
end;
$$;

drop trigger if exists trg_update_rank on public.user_stats;
create trigger trg_update_rank
before insert or update of xp on public.user_stats
for each row execute function public.update_rank_from_xp();

-- =========================================
-- AWARD XP ON COMPLETION
-- =========================================
create or replace function public.award_xp_on_completion()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  reward integer;
begin
  if new.status = 'completed'
    and old.status is distinct from 'completed'
    and old.xp_awarded = false
  then
    select reward_xp into reward
    from public.jobs
    where id = new.job_id;

    update public.user_stats
    set xp = xp + coalesce(reward, 0)
    where user_id = new.user_id;

    new.xp_awarded = true;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_award_xp_on_completion on public.job_applications;
create trigger trg_award_xp_on_completion
before update of status on public.job_applications
for each row execute function public.award_xp_on_completion();

-- =========================================
-- AUTO-ADD PARTY LEADER
-- =========================================
create or replace function public.add_party_leader_as_member()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.leader_id is not null then
    insert into public.party_members (party_id, user_id, role)
    values (new.id, new.leader_id, 'leader')
    on conflict (party_id, user_id) do update set role = 'leader';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_add_party_leader_as_member on public.parties;
create trigger trg_add_party_leader_as_member
after insert on public.parties
for each row execute function public.add_party_leader_as_member();
